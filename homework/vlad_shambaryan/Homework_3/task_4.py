import math  # Импортируем модуль math для использования математических функций

# Задаем длины катетов треугольника a и b
a = 4
b = 2

# Вычисление гипотенузы треугольника по теореме Пифагора: корень квадратный из суммы квадратов катетов
c = math.sqrt(a**2 + b**2)

# Вычисление площади прямоугольного треугольника: половина произведения катетов
s = 0.5 * a * b

# Выводим результаты
print(c)  # Вывод длины гипотенузы
print(s)  # Вывод площади треугольника
