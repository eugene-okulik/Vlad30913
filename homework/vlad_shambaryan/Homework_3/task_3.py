import math  # Импортируем модуль math для использования математических функций

# Задаем значения переменных x и y
x = 4
y = 2

# Вычисляем среднее арифметическое: сумма x и y делится на 2
arithmetic = (x + y) / 2

# Вычисляем среднее геометрическое: квадратный корень из произведения x и y
geometric = math.sqrt(x * y)

# Выводим результаты
print(arithmetic)  # Вывод среднего арифметического
print(geometric)   # Вывод среднего геометрического
